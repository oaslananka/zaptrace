_OracleResult = KiCadErcResult | KiCadDrcResult


def _report_items(violation: dict[str, Any]) -> list[dict[str, Any]]:
    items = violation.get("items", [])
    return [item for item in items if isinstance(item, dict)] if isinstance(items, list) else []


def _item_descriptions(violation: dict[str, Any]) -> list[str]:
    return [str(item.get("description", "")) for item in _report_items(violation) if item.get("description")]


def _first_report_position(violation: dict[str, Any]) -> tuple[float, float] | None:
    direct = violation.get("position")
    if isinstance(direct, dict) and "x" in direct and "y" in direct:
        return (float(direct["x"]), float(direct["y"]))
    for item in _report_items(violation):
        pos = item.get("pos")
        if isinstance(pos, dict) and "x" in pos and "y" in pos:
            return (float(pos["x"]), float(pos["y"]))
    return None


def _erc_violation_rows(raw: dict[str, Any]) -> list[tuple[dict[str, Any], str]]:
    sheets = raw.get("sheets")
    if isinstance(sheets, list):
        rows: list[tuple[dict[str, Any], str]] = []
        for sheet in sheets:
            if not isinstance(sheet, dict):
                continue
            sheet_path = str(sheet.get("path", ""))
            violations = sheet.get("violations", [])
            if isinstance(violations, list):
                rows.extend((violation, sheet_path) for violation in violations if isinstance(violation, dict))
        return rows
    violations = raw.get("violations", [])
    if not isinstance(violations, list):
        return []
    return [(violation, str(violation.get("sheet", ""))) for violation in violations if isinstance(violation, dict)]


def _erc_item(violation: dict[str, Any], *, sheet_path: str) -> KiCadErcItem:
    descriptions = _item_descriptions(violation)
    source = _report_items(violation) or violation.get("source")
    return KiCadErcItem(
        rule=str(violation.get("rule") or violation.get("type") or ""),
        severity=str(violation.get("severity", "error")),
        message=str(violation.get("message") or violation.get("description") or ""),
        sheet=str(violation.get("sheet") or sheet_path),
        item=str(violation.get("item") or (descriptions[0] if descriptions else "")),
        comment=list(violation.get("comment", [])) if isinstance(violation.get("comment", []), list) else [],
        source=source if isinstance(source, list) else None,
    )


def _drc_violation_rows(raw: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for key in ("violations", "unconnected_items", "schematic_parity"):
        values = raw.get(key, [])
        if isinstance(values, list):
            rows.extend(value for value in values if isinstance(value, dict))
    return rows


def _drc_item(violation: dict[str, Any]) -> KiCadDrcItem:
    descriptions = _item_descriptions(violation)
    return KiCadDrcItem(
        rule=str(violation.get("rule") or violation.get("type") or ""),
        severity=str(violation.get("severity", "error")),
        message=str(violation.get("message") or violation.get("description") or ""),
        layer=str(violation.get("layer", "")),
        position=_first_report_position(violation),
        code=int(violation.get("code", 0)),
        comment=list(violation.get("comment", [])) if "comment" in violation else descriptions,
    )


def _count_result_severity(result: _OracleResult, severity: str) -> None:
    if severity == "error":
        result.errors += 1
    elif severity == "warning":
        result.warnings += 1


def _apply_check_metadata(
    result: _OracleResult,
    *,
    elapsed_ms: float,
    version: str,
    cli_path: str,
    command: list[str],
    exit_code: int,
    report_path: Path,
) -> _OracleResult:
    result.available = True
    result.duration_ms = elapsed_ms
    result.version = version
    result.cli_path = cli_path
    result.command = command.copy()
    result.exit_code = exit_code
    result.report_path = _portable_path_text(report_path)
    result.report_sha256 = _sha256_if_readable(report_path)
    return result


def _finalize_check_result(
    result: _OracleResult,
    *,
    process: subprocess.CompletedProcess[str],
    check_name: str,
    exit_code_violations: bool,
) -> _OracleResult:
    # KiCad returns 5 when --exit-code-violations sees any reported finding,
    # including warnings. Preserve the existing legacy code-3 compatibility,
    # but let a parsed JSON report remain authoritative for finding severity;
    # other non-zero codes are execution failures.
    if exit_code_violations and process.returncode not in {0, 3, 5}:
        result.success = False
        result.message = process.stderr.strip() or f"{check_name} failed (exit {process.returncode})"
    result.success = result.success or process.returncode == 0
    result.message = result.message or (f"{check_name} complete: {result.errors} errors, {result.warnings} warnings")
    return result


