def _secure_temp_report_path(*, suffix: str) -> Path:
    """Create and close a unique temporary report path for kicad-cli output."""
    with tempfile.NamedTemporaryFile(prefix="zaptrace-kicad-", suffix=suffix, delete=False) as handle:
        return Path(handle.name)


def _portable_path_text(path: str | Path) -> str:
    """Return a platform-neutral path string for evidence payloads."""
    return str(path).replace("\\", "/")


def _sha256_if_readable(path: Path) -> str:
    """Return SHA-256 for a file path when readable, else an empty string."""
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return ""


@dataclass
class KiCadResult:
    """Base result for any KiCad oracle operation."""

    available: bool
    """Whether the KiCad CLI was found and executed."""

    success: bool = False
    """Whether the operation completed without errors."""

    message: str = ""
    """Human-readable summary."""

    duration_ms: float = 0.0
    """Wall-clock time for the operation."""

    version: str = ""
    """Detected kicad-cli version, when available."""

    cli_path: str = ""
    """Resolved kicad-cli executable path, when available."""

    command: list[str] = field(default_factory=list)
    """Executed command, if any."""

    exit_code: int | None = None
    """Process exit code, if a command ran."""

    report_path: str | None = None
    """Path to the structured report generated by kicad-cli, if any."""

    report_sha256: str = ""
    """SHA-256 hex digest of report_path, if readable."""

    @property
    def error(self) -> str:
        """Human-readable error when the operation failed, else empty."""
        return self.message if not self.success else ""


@dataclass
class KiCadErcItem:
    """A single ERC violation from the KiCad report."""

    rule: str = ""
    severity: str = "error"
    message: str = ""
    sheet: str = ""
    item: str = ""  # e.g. "J1:1 -> U1:10"
    comment: list[str] = field(default_factory=list)
    source: list[dict] | None = None


@dataclass
class KiCadErcResult(KiCadResult):
    """ERC check result with structured violations."""

    violations: list[KiCadErcItem] = field(default_factory=list)
    errors: int = 0
    warnings: int = 0

    @property
    def passed(self) -> bool:
        return self.success and self.errors == 0

    def to_oracle_evidence(
        self,
        *,
        check: str = "schematic_erc",
        approval_id: str = "",
        waiver_reason: str = "",
    ) -> Any:
        """Convert this ERC result into proof-pack KiCad oracle evidence."""
        from zaptrace.proof.manifest import KiCadOracleEvidence

        if not self.available:
            status = "skipped"
            skip_reason = self.message or "kicad-cli not available"
        elif self.passed:
            status = "passed"
            skip_reason = ""
        elif approval_id and waiver_reason:
            status = "waived"
            skip_reason = ""
        else:
            status = "failed"
            skip_reason = ""
        return KiCadOracleEvidence(
            check=check,
            status=status,
            version=self.version,
            cli_path=self.cli_path,
            command=self.command,
            exit_code=self.exit_code,
            report_path=self.report_path,
            report_sha256=self.report_sha256,
            errors=self.errors,
            warnings=self.warnings,
            message=self.message,
            skip_reason=skip_reason,
            approval_id=approval_id,
            waiver_reason=waiver_reason,
        )

    @property
    def violation_count(self) -> int:
        return len(self.violations)

    @property
    def error_count(self) -> int:
        return self.errors

    @property
    def warning_count(self) -> int:
        return self.warnings


