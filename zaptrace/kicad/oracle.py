# Oracle class
# ======================================================================


class KiCadOracle:
    """Detect and interact with the KiCad CLI.

    Usage:
        oracle = KiCadOracle()
        if oracle.available:
            print(oracle.version)
            erc = oracle.run_erc("project.kicad_pro")
    """

    def __init__(self, cli_path: str | None = None) -> None:
        self._cli_path: str | None = cli_path
        self._version: str = ""
        self._detect()

    # ------------------------------------------------------------------
    # Public properties
    # ------------------------------------------------------------------

    @property
    def available(self) -> bool:
        return self._cli_path is not None

    @property
    def cli_path(self) -> str | None:
        return self._cli_path

    @property
    def version(self) -> str:
        if not self._cli_path:
            return ""
        if not self._version:
            self._version = self._capture_version()
        return self._version

    # ------------------------------------------------------------------
    # Detection
    # ------------------------------------------------------------------

    def _detect(self) -> None:
        """Locate the kicad-cli binary."""
        if self._cli_path:
            self._cli_path = self._resolve(self._cli_path)
            return

        # Try PATH first
        resolved = shutil.which("kicad-cli")
        if resolved:
            self._cli_path = resolved
            return

        # Try known install paths
        for p in _COMMON_KICAD_PATHS:
            if self._resolve(p):
                self._cli_path = p
                return

        self._cli_path = None

    @staticmethod
    def _resolve(path: str) -> str | None:
        """Resolve *path* — return the absolute path if it exists."""
        if not path:
            return None
        # shutil.which already resolved — just check
        if os.path.isfile(path):
            return os.path.abspath(path)
        resolved = shutil.which(path)
        if resolved and os.path.isfile(resolved):
            return resolved
        return None

    def _capture_version(self) -> str:
        """Run ``kicad-cli --version`` and return the output."""
        if not self._cli_path:
            return ""
        try:
            result = subprocess.run(
                [self._cli_path, "--version"],
                capture_output=True,
                text=True,
                timeout=10,
            )
            if result.returncode == 0:
                return result.stdout.strip()
            return ""
        except (subprocess.TimeoutExpired, OSError):
            return ""

    # ------------------------------------------------------------------
    # ERC
    # ------------------------------------------------------------------

    def _run_json_check(
        self,
        *,
        base: _OracleResult,
        command: list[str],
        report_path: Path,
        output_path: str | Path | None,
        timeout: int,
        started_at: float,
        parser: Callable[[dict[str, Any]], _OracleResult],
        check_name: str,
        exit_code_violations: bool,
    ) -> _OracleResult:
        import time

        try:
            process = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
            elapsed_ms = (time.perf_counter() - started_at) * 1000
            base = _apply_check_metadata(
                base,
                elapsed_ms=elapsed_ms,
                version=self.version,
                cli_path=self._cli_path or "",
                command=command,
                exit_code=process.returncode,
                report_path=report_path,
            )
            if report_path.exists():
                parsed = parser(json.loads(report_path.read_text(encoding="utf-8")))
                base = _apply_check_metadata(
                    parsed,
                    elapsed_ms=elapsed_ms,
                    version=self.version,
                    cli_path=self._cli_path or "",
                    command=command,
                    exit_code=process.returncode,
                    report_path=report_path,
                )
            return _finalize_check_result(
                base,
                process=process,
                check_name=check_name,
                exit_code_violations=exit_code_violations,
            )
        except FileNotFoundError:
            base.message = f"KiCad CLI not found at {self._cli_path}"
        except subprocess.TimeoutExpired:
            base.message = f"{check_name} timed out after {timeout}s"
        except json.JSONDecodeError as error:
            base.message = f"{check_name} output parse error: {error}"
        except Exception as error:
            base.message = f"{check_name} unexpected error: {error}"
        finally:
            if not output_path and report_path.exists():
                with suppress(OSError):
                    report_path.unlink()
        return base

    def run_erc(
        self,
        project_file: str | Path,
        *,
        output_path: str | Path | None = None,
        timeout: int = 120,
        severity: str = "all",
        exit_code_violations: bool = True,
    ) -> KiCadErcResult:
        """Run Electrical Rules Check via ``kicad-cli sch erc``.

        Args:
            project_file: Path to a ``.kicad_pro`` project file.
            output_path: Optional path for the JSON report. If omitted a
                temporary file is used.
            timeout: Max seconds to wait for the CLI.
            severity: ``"all"``, ``"error"``, or ``"warning"``.
            exit_code_violations: If True, KiCad returns a non-zero code when
                findings exist; parsed report severity still determines pass/fail.

        Returns:
            ``KiCadErcResult`` with structured violations.
        """
        import time

        base = KiCadErcResult(
            available=self.available,
            version=self.version,
            cli_path=self._cli_path or "",
        )
        if not self._cli_path:
            base.message = "KiCad CLI not found"
            return base

        started_at = time.perf_counter()
        project = Path(project_file)
        if not project.exists():
            base.message = f"Project file not found: {project}"
            base.duration_ms = (time.perf_counter() - started_at) * 1000
            return base

        report_path = Path(output_path) if output_path else _secure_temp_report_path(suffix="-erc.json")
        command = [
            self._cli_path,
            "sch",
            "erc",
            str(project),
            "--format",
            "json",
            "--output",
            str(report_path),
            f"--severity-{severity}",
        ]
        if exit_code_violations:
            command.append("--exit-code-violations")
        base.command = command.copy()
        base.report_path = _portable_path_text(report_path)
        base.report_sha256 = _sha256_if_readable(report_path)
        return cast(
            KiCadErcResult,
            self._run_json_check(
                base=base,
                command=command,
                report_path=report_path,
                output_path=output_path,
                timeout=timeout,
                started_at=started_at,
                parser=self._parse_erc_json,
                check_name="ERC",
                exit_code_violations=exit_code_violations,
            ),
        )

    @staticmethod
    def _parse_erc_json(raw: dict[str, Any]) -> KiCadErcResult:
        """Parse legacy and KiCad 10 ERC JSON reports into a structured result."""
        result = KiCadErcResult(available=True, success=True)
        rows = _erc_violation_rows(raw)

        for violation, sheet_path in rows:
            item = _erc_item(violation, sheet_path=sheet_path)
            result.violations.append(item)
            _count_result_severity(result, item.severity)

        result.message = f"{result.errors} ERC errors, {result.warnings} warnings"
        result.success = result.errors == 0
        return result

    # ------------------------------------------------------------------
    # DRC
    # ------------------------------------------------------------------

    def run_drc(
        self,
        pcb_file: str | Path,
        *,
        output_path: str | Path | None = None,
        timeout: int = 120,
        severity: str = "all",
        exit_code_violations: bool = True,
        schematic_parity: bool = False,
    ) -> KiCadDrcResult:
        """Run Design Rules Check via ``kicad-cli pcb drc``.

        Args:
            pcb_file: Path to a ``.kicad_pcb`` board file.
            output_path: Optional path for the JSON report.
            timeout: Max seconds to wait for the CLI.
            severity: ``"all"``, ``"error"``, or ``"warning"``.
            exit_code_violations: If True, KiCad returns a non-zero code when
                findings exist; parsed report severity still determines pass/fail.
            schematic_parity: Also check schematic-PCB parity.

        Returns:
            ``KiCadDrcResult`` with structured violations.
        """
        import time

        base = KiCadDrcResult(
            available=self.available,
            version=self.version,
            cli_path=self._cli_path or "",
        )
        if not self._cli_path:
            base.message = "KiCad CLI not found"
            return base

        started_at = time.perf_counter()
        board = Path(pcb_file)
        if not board.exists():
            base.message = f"PCB file not found: {board}"
            base.duration_ms = (time.perf_counter() - started_at) * 1000
            return base

        report_path = Path(output_path) if output_path else _secure_temp_report_path(suffix="-drc.json")
        command = [
            self._cli_path,
            "pcb",
            "drc",
            str(board),
            "--format",
            "json",
            "--output",
            str(report_path),
            f"--severity-{severity}",
        ]
        if exit_code_violations:
            command.append("--exit-code-violations")
        if schematic_parity:
            command.append("--schematic-parity")
        base.command = command.copy()
        base.report_path = _portable_path_text(report_path)
        base.report_sha256 = _sha256_if_readable(report_path)
        return cast(
            KiCadDrcResult,
            self._run_json_check(
                base=base,
                command=command,
                report_path=report_path,
                output_path=output_path,
                timeout=timeout,
                started_at=started_at,
                parser=self._parse_drc_json,
                check_name="DRC",
                exit_code_violations=exit_code_violations,
            ),
        )

    @staticmethod
    def _parse_drc_json(raw: dict[str, Any]) -> KiCadDrcResult:
        """Parse legacy and KiCad 10 DRC JSON reports into a structured result."""
        result = KiCadDrcResult(available=True, success=True)

        for violation in _drc_violation_rows(raw):
            item = _drc_item(violation)
            result.violations.append(item)
            _count_result_severity(result, item.severity)

        result.message = f"{result.errors} DRC errors, {result.warnings} warnings"
        result.success = result.errors == 0
        return result

    def __repr__(self) -> str:
        if self.available:
            return f"<KiCadOracle {self._cli_path} v{self.version}>"
        return "<KiCadOracle unavailable>"


