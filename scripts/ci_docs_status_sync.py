def _claim_checks(
    erc_count: int,
    drc_count: int,
    design_tool_count: int,
    mcp_tool_count: int,
) -> list[tuple[re.Pattern[str], int, str]]:
    return [
        (re.compile(r"(?<![\d.])(\d+)[ \t]+ERC[ \t]+rules\b", re.IGNORECASE), erc_count, "ERC rules"),
        (re.compile(r"\bERC[ \t]*\((\d+)[ \t]+rules?\)", re.IGNORECASE), erc_count, "ERC rules"),
        (re.compile(r"(?<![\d.])(\d+)[ \t]+DRC[ \t]+rules\b", re.IGNORECASE), drc_count, "DRC rules"),
        (re.compile(r"\bDRC[ \t]*\((\d+)[ \t]+rules?\)", re.IGNORECASE), drc_count, "DRC rules"),
        (
            re.compile(r"(?<![\d.])(\d+)[ \t]+agent[- ]facing[ \t]+tools\b", re.IGNORECASE),
            design_tool_count,
            "agent design tools",
        ),
        (re.compile(r"(?<![\d.])(\d+)[ \t]+design[ \t]+tools\b", re.IGNORECASE), design_tool_count, "design tools"),
        (
            re.compile(r"Tool Registry[^(\n]*\((\d+)[ \t]+tools", re.IGNORECASE),
            design_tool_count,
            "registry tools",
        ),
        (re.compile(r"MCP server[ \t]*\((\d+)[ \t]+tools\)", re.IGNORECASE), mcp_tool_count, MCP_TOOLS_LABEL),
        (re.compile(r"(?<![\d.])(\d+)[ \t]+tools[ \t]+total\b", re.IGNORECASE), mcp_tool_count, MCP_TOOLS_LABEL),
        (re.compile(r"(?<![\d.])(\d+)[ \t]+exposed[ \t]+tools\b", re.IGNORECASE), mcp_tool_count, MCP_TOOLS_LABEL),
    ]


def _validate_repository_facts(capabilities: dict[str, bool]) -> list[str]:
    errors = [
        f"repository capability evidence missing or incomplete: {name}"
        for name, available in capabilities.items()
        if not available
    ]
    errors.extend(f"mkdocs.yml: public page missing from navigation: docs/{gap}" for gap in navigation_gaps())
    errors.extend(
        f"public docs contain internal implementation material: {path}" for path in internal_public_plan_paths()
    )
    return errors


def _validate_current_state_document(path: Path = Path("docs/strategy/current-state-audit.md")) -> list[str]:
    """Validate machine-derived claims that are allowed in the current-state audit."""
    profile = component_library_profile()
    checks = [
        (
            re.compile(r"(?<![\d.])(\d+)[ \t]+component[ \t]+records\b", re.IGNORECASE),
            int(profile["component_count"]),
            "component records",
        )
    ]
    errors = _validate_document(path, checks)
    text = path.read_text(encoding="utf-8", errors="ignore")
    for required in (COMPONENT_TRUST_BASELINE_PATH, "scripts/ci_docs_status_sync.py"):
        if required not in text:
            errors.append(f"{path}: missing current-state evidence source {required}")
    return errors


def _validate_release_documentation() -> list[str]:
    errors: list[str] = []
    document = Path("docs/development/validation-environment.md").read_text(encoding="utf-8")
    required_arguments = (
        "--risky-package-reviewed",
        '--risky-package-approval-id "GENERATED-BOARD-BASELINE-REVIEW-2026-07-22"',
    )
    for argument in required_arguments:
        if argument not in document:
            errors.append(f"docs/development/validation-environment.md: missing CI release argument {argument}")
    readme = Path("README.md").read_text(encoding="utf-8")
    discussions_url = "https://github.com/oaslananka/zaptrace/discussions"
    if discussions_url not in readme:
        errors.append("README.md: missing the enabled GitHub Discussions support channel")
    if "GitHub Discussions is currently disabled" in readme:
        errors.append("README.md: claims GitHub Discussions is disabled even though the channel is enabled")
    return errors


def _validate_document(path: Path, checks: list[tuple[re.Pattern[str], int, str]]) -> list[str]:
    errors: list[str] = []
    text = path.read_text(encoding="utf-8", errors="ignore")
    errors.extend(
        f"{path}: banned stale reference {banned!r}: {reason}"
        for banned, reason in BANNED_REFERENCES.items()
        if banned in text
    )
    for pattern, actual, label in checks:
        for match in pattern.finditer(text):
            claimed = int(match.group(1))
            if claimed != actual:
                errors.append(f"{path}: claims {claimed} {label} but code has {actual}")
    return errors


def validate_docs() -> dict[str, Any]:
    erc_count = actual_erc_rule_count()
    drc_count = actual_drc_rule_count()
    tool_count = actual_tool_count()
    mcp_admin_tools = actual_mcp_admin_tool_names()
    mcp_tool_count = tool_count + len(mcp_admin_tools)
    capabilities = repository_capabilities()
    component_library = component_library_profile()
    revision = source_revision()
    checks = _claim_checks(erc_count, drc_count, tool_count, mcp_tool_count)

    errors = _validate_repository_facts(capabilities)
    if revision == "unknown":
        errors.append("repository revision identity is unavailable")
    errors.extend(_validate_release_documentation())
    errors.extend(_validate_current_state_document())
    for path in _iter_docs():
        if path != Path("docs/strategy/current-state-audit.md"):
            errors.extend(_validate_document(path, checks))

    return {
        "passed": not errors,
        "erc_rule_count": erc_count,
        "drc_rule_count": drc_count,
        "tool_count": tool_count,
        "mcp_admin_tools": mcp_admin_tools,
        "mcp_tool_count": mcp_tool_count,
        "capabilities": capabilities,
        "component_library": component_library,
        "source_revision": revision,
        "fact_sources": {
            "component_library": COMPONENT_TRUST_BASELINE_PATH,
            "docs_status": "scripts/ci_docs_status_sync.py",
            "kicad_project_import": "zaptrace/kicad/project_importer.py",
            "release": ".github/workflows/release.yml",
            "ruleset": "config/github-main-ruleset.json",
        },
        "navigation_gap_count": len(navigation_gaps()),
        "errors": errors,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Validate docs/status sync guard")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    result = validate_docs()
    if args.output:
        args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if not result["passed"]:
        for error in result["errors"]:
            print(error)
        return 1
    print(
        "docs-status-sync ok: "
        f"ERC rules={result['erc_rule_count']}, "
        f"DRC rules={result['drc_rule_count']}, "
        f"design tools={result['tool_count']}, "
        f"MCP-exposed tools={result['mcp_tool_count']}"
    )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
