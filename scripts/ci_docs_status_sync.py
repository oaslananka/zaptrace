def _list_len_assignment(path: str, name: str) -> int:
    """Return the element count of a module-level ``name = [...]`` list literal.

    Handles both plain assignments (``name = [...]``) and annotated
    assignments (``name: list[T] = [...]``).
    """
    tree = ast.parse(Path(path).read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            targets = [t for t in node.targets if isinstance(t, ast.Name) and t.id == name]
            value = node.value
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == name:
            targets = [node.target]
            value = node.value
        else:
            continue
        if targets and isinstance(value, ast.List):
            return len(value.elts)
    raise RuntimeError(f"Could not find {name} in {path}")


def actual_erc_rule_count() -> int:
    return _list_len_assignment("zaptrace/erc/runner.py", "_ALL_RULES")


def actual_drc_rule_count() -> int:
    return _list_len_assignment("zaptrace/ee/drc/engine.py", "_ALL_CHECKS")


def actual_tool_count() -> int:
    """Return the declarative public design-tool count."""
    return _list_len_assignment("zaptrace/agent/tool_impls/registry.py", "_TOOL_ORDER")


def actual_mcp_admin_tool_names() -> list[str]:
    """Return module-level administrative tools registered directly on FastMCP."""
    tree = ast.parse(Path("zaptrace/mcp/server.py").read_text(encoding="utf-8"))
    names: list[str] = []
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            target = decorator.func if isinstance(decorator, ast.Call) else decorator
            if (
                isinstance(target, ast.Attribute)
                and target.attr == "tool"
                and isinstance(target.value, ast.Name)
                and target.value.id == "server"
            ):
                names.append(node.name)
                break
    return sorted(names)


def actual_mcp_tool_count() -> int:
    """Return all MCP-exposed tools: design registry plus session administration."""
    return actual_tool_count() + len(actual_mcp_admin_tool_names())


def _iter_docs() -> list[Path]:
    paths: list[Path] = []
    for root in ROOTS:
        if root.is_file():
            paths.append(root)
        elif root.is_dir():
            paths.extend(path for path in root.rglob("*") if path.suffix.lower() in {".md", ".txt", ".json"})
    return sorted(paths)


def component_library_profile(path: Path = Path(COMPONENT_TRUST_BASELINE_PATH)) -> dict[str, Any]:
    """Return the committed component-library baseline used by CI."""
    data = json.loads(path.read_text(encoding="utf-8"))
    tiers = Counter(str(value) for value in data.get("component_tiers", {}).values())
    return {
        "source": str(path).replace("\\", "/"),
        "component_count": int(data["component_count"]),
        "schema_version": str(data.get("component_schema_version", "unknown")),
        "trust_tier_counts": dict(sorted(tiers.items())),
    }


def source_revision() -> str:
    """Return the exact repository revision that produced the docs-status report."""
    try:
        completed = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    revision = completed.stdout.strip()
    return revision if re.fullmatch(r"[0-9a-fA-F]{40}", revision) else "unknown"


def internal_public_plan_paths(root: Path = Path("docs")) -> list[str]:
    """Return internal implementation-plan paths that must not be public docs."""
    internal_root = root / "superpowers"
    if not internal_root.exists():
        return []
    return sorted(str(path).replace("\\", "/") for path in internal_root.rglob("*") if path.is_file())


def navigation_gaps(root: Path = Path("docs"), config: Path = Path("mkdocs.yml")) -> list[str]:
    """Return Markdown pages not referenced by the MkDocs navigation."""
    text = config.read_text(encoding="utf-8")
    navigated = set(re.findall(r":\s*([^\s#]+\.md)\s*$", text, re.MULTILINE))
    pages = {str(path.relative_to(root)).replace("\\", "/") for path in root.rglob("*.md")}
    return sorted(pages - navigated)


